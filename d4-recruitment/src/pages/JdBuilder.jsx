import React, { useState } from 'react';
import { Button, Badge, Card, colors } from '@d4/design-system';

// Read from runtime config (window.__D4_CONFIG__, injected via config.js —
// see d4-recruitment/public/config.js and d4-parent/public/config.js) so
// this same build can point at QA/UAT/prod's recruitment-api without a
// rebuild. Falls back to localhost only so standalone dev still works if
// config.js somehow didn't load.
const RECRUITMENT_API_BASE =
  (typeof window !== 'undefined' && window.__D4_CONFIG__ && window.__D4_CONFIG__.RECRUITMENT_API_URL) ||
  'http://localhost:8002';

export default function JdBuilder() {
  const [title, setTitle] = useState('');
  const [department, setDepartment] = useState('');
  const [skillInput, setSkillInput] = useState('');
  const [skills, setSkills] = useState([]);
  const [status, setStatus] = useState('idle'); // idle | generating | done | error
  const [generated, setGenerated] = useState(null);
  const [errorMessage, setErrorMessage] = useState('');

  const addSkill = (e) => {
    if (e.key !== 'Enter') return;
    e.preventDefault();
    const value = skillInput.trim();
    if (value && !skills.includes(value)) {
      setSkills([...skills, value]);
    }
    setSkillInput('');
  };

  const removeSkill = (skill) => {
    setSkills(skills.filter((s) => s !== skill));
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setStatus('generating');
    setErrorMessage('');
    try {
      const response = await fetch(`${RECRUITMENT_API_BASE}/api/jd/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ title, department, skills }),
      });
      if (!response.ok) {
        throw new Error(`API responded with ${response.status}`);
      }
      const data = await response.json();
      setGenerated(data);
      setStatus('done');
    } catch (err) {
      setErrorMessage(
        `Couldn't reach the recruitment API at ${RECRUITMENT_API_BASE}. Make sure it's running ` +
          "(uvicorn main:app --port 8002 inside d4-recruitment-api)."
      );
      setStatus('error');
    }
  };

  const inputStyle = {
    width: '100%',
    padding: '8px 10px',
    borderRadius: 6,
    border: `1px solid ${colors.border}`,
    fontSize: 14,
    boxSizing: 'border-box',
  };

  return (
    <div style={{ maxWidth: 480 }}>
      <h2 style={{ marginTop: 0 }}>JD Builder</h2>
      <form onSubmit={handleSubmit}>
        <div style={{ marginBottom: 16 }}>
          <label style={{ display: 'block', marginBottom: 6, fontWeight: 600 }}>Job Title</label>
          <input
            style={inputStyle}
            type="text"
            value={title}
            onChange={(e) => setTitle(e.target.value)}
            placeholder="e.g. Senior Frontend Engineer"
          />
        </div>
        <div style={{ marginBottom: 16 }}>
          <label style={{ display: 'block', marginBottom: 6, fontWeight: 600 }}>Department</label>
          <input
            style={inputStyle}
            type="text"
            value={department}
            onChange={(e) => setDepartment(e.target.value)}
            placeholder="e.g. Engineering"
          />
        </div>
        <div style={{ marginBottom: 20 }}>
          <label style={{ display: 'block', marginBottom: 6, fontWeight: 600 }}>Skills</label>
          <input
            style={inputStyle}
            type="text"
            value={skillInput}
            onChange={(e) => setSkillInput(e.target.value)}
            onKeyDown={addSkill}
            placeholder="Type a skill and press Enter"
          />
          <div style={{ display: 'flex', flexWrap: 'wrap', gap: 6, marginTop: 10 }}>
            {skills.map((skill) => (
              <span key={skill} onClick={() => removeSkill(skill)} style={{ cursor: 'pointer' }} title="Click to remove">
                <Badge variant="neutral">{skill} ✕</Badge>
              </span>
            ))}
          </div>
        </div>
        <Button type="submit" variant="primary" disabled={status === 'generating'}>
          {status === 'generating' ? 'Generating…' : 'Create Job Description'}
        </Button>
      </form>

      {status === 'error' ? (
        <p style={{ marginTop: 16, fontSize: 13, color: colors.accent }}>{errorMessage}</p>
      ) : null}

      {status === 'done' && generated ? (
        <div style={{ marginTop: 20 }}>
          <Card title={`${generated.title} — ${generated.department}`}>
            <p style={{ margin: 0, fontSize: 14, lineHeight: 1.6, color: colors.text }}>
              {generated.description}
            </p>
            <p style={{ marginTop: 12, marginBottom: 0, fontSize: 12, color: colors.textMuted }}>
              Generated by recruitment-api ({generated.generated_by})
            </p>
          </Card>
        </div>
      ) : null}
    </div>
  );
}
